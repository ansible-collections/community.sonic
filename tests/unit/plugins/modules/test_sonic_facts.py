def seed(fake_swsscommon, mgmt_vrf=None):
    data = {
        'DEVICE_METADATA': {'localhost': DEVICE_METADATA},
        'PORT': PORT,
        'FEATURE': FEATURE,
        'VLAN_MEMBER': {'Vlan100|Ethernet0': {'tagging_mode': 'untagged'}},
    }
    if mgmt_vrf is not None:
        data['MGMT_VRF_CONFIG'] = {'vrf_global': mgmt_vrf}
    fake_swsscommon.seed(data)


@pytest.fixture
def files(monkeypatch):
    """Replace the file reads of the module with an in-memory ``{path: content}`` map.

    A path that is missing from the map raises ``IOError`` like an unreadable file would.
    """
    contents = {
        sonic_facts.SONIC_VERSION_FILE: SONIC_VERSION_YML,
        sonic_facts.SONIC_ENVIRONMENT_FILE: SONIC_ENVIRONMENT,
        sonic_facts.SAVED_CONFIG_DB_FILE: json.dumps(SAVED_CONFIG_DB),
    }

    def _read(path):
        if path not in contents:
            raise IOError(13, 'Permission denied', path)
        return contents[path]

    monkeypatch.setattr(sonic_facts, 'read_text_file', _read)
    return contents


@pytest.fixture
def warnings(monkeypatch):
    """Collect ``module.warn()`` messages."""
    collected = []
    monkeypatch.setattr(basic.AnsibleModule, 'warn', lambda self, msg: collected.append(msg))
    return collected


# -- pure logic ------------------------------------------------------------------

@pytest.mark.parametrize('requested,expected', (
    (None, {'min'}),
    ([], {'min'}),
    (['min'], {'min'}),
    (['all'], {'min', 'config_db', 'saved_config_db'}),
    (['config_db'], {'min', 'config_db'}),
    (['min', 'config_db'], {'min', 'config_db'}),
    (['saved_config_db'], {'min', 'saved_config_db'}),
    (['!saved_config_db'], {'min', 'config_db'}),
    (['!config_db', '!saved_config_db'], {'min'}),
    (['all', '!min'], {'config_db', 'saved_config_db'}),
    (['config_db', '!min'], {'config_db'}),
    (['!all'], {'min'}),
    (['!all', 'config_db'], {'min'}),
    (['!all', '!min'], set()),
))
def test_resolve_subsets(requested, expected):
    assert sonic_facts.resolve_subsets(requested) == expected


def test_resolve_subsets_unknown():
    with pytest.raises(ValueError) as excinfo:
        sonic_facts.resolve_subsets(['network'])
    assert 'unknown gather_subset "network"' in str(excinfo.value)


def test_parse_flat_yaml():
    parsed = sonic_facts.parse_flat_yaml(SONIC_VERSION_YML)
    assert parsed['build_version'] == 'SONiC.202311.0-dirty-20240101.123456'
    assert parsed['debian_version'] == '12.1'
    assert parsed['asic_type'] == 'vs'
    assert parsed['asic_subtype'] == ''
    assert parsed['build_number'] == '42'
    assert parsed['build_date'] == 'Mon Jan 01 12:00:00 UTC 2024'
    assert parsed['built_by'] == 'user@buildhost'
    assert sonic_facts.parse_flat_yaml('---\n# comment\n\nkey: "a: b"\nnoval\n') == {'key': 'a: b'}
    assert sonic_facts.parse_flat_yaml(b'build_version: x\n') == {'build_version': 'x'}


def test_parse_environment():
    parsed = sonic_facts.parse_environment(SONIC_ENVIRONMENT)
    assert parsed == {
        'SONIC_VERSION': 'SONiC.202311.0-dirty-20240101.123456',
        'PLATFORM': 'x86_64-kvm_x86_64-r0',
        'HWSKU': 'Force10-S6000',
        'DEVICE_TYPE': 'LeafRouter',
        'ASIC_TYPE': 'vs',
    }
    assert sonic_facts.parse_environment('export A="x=y"\n\n# c\nB=\'1\'\nnoeq\n') == {'A': 'x=y', 'B': '1'}


def test_build_min_facts_prefers_device_metadata_and_falls_back():
    version_info = sonic_facts.parse_flat_yaml(SONIC_VERSION_YML)
    environment = sonic_facts.parse_environment(SONIC_ENVIRONMENT)
    facts = sonic_facts.build_min_facts(
        {'hostname': 'leaf1', 'hwsku': 'Other-SKU', 'platform': 'x86_64-other'},
        {'mgmtVrfEnabled': 'true'}, FEATURE, version_info, environment)
    assert facts['hwsku'] == 'Other-SKU'
    assert facts['platform'] == 'x86_64-other'
    assert facts['hostname'] == 'leaf1'
    assert facts['mac'] is None
    assert facts['device_type'] == 'LeafRouter'
    assert facts['mgmt_vrf_enabled'] is True

    facts = sonic_facts.build_min_facts({}, {}, {}, version_info, environment)
    assert facts['hwsku'] == 'Force10-S6000'
    assert facts['platform'] == 'x86_64-kvm_x86_64-r0'
    assert facts['asic_type'] == 'vs'
    assert facts['hostname'] is None
    assert facts['mgmt_vrf_enabled'] is False
    assert facts['features'] == {}

    facts = sonic_facts.build_min_facts({}, {}, {}, {}, {})
    assert facts['version'] is None
    assert facts['build'] == dict((k, None) for k in EXPECTED_BUILD)
    assert facts['version_info'] == {}


