def test_negated_subsets(fake_swsscommon, run_module, files, warnings):
    seed(fake_swsscommon)
    sonic = run_module(sonic_facts, dict(gather_subset=['!saved_config_db']))['ansible_facts']['sonic']
    assert 'config_db' in sonic
    assert 'saved_config_db' not in sonic
    assert sonic['hwsku'] == 'Force10-S6000'

    sonic = run_module(sonic_facts, dict(gather_subset=['config_db', '!min']))['ansible_facts']['sonic']
    assert list(sonic) == ['config_db']

    sonic = run_module(sonic_facts, dict(gather_subset=['!all']))['ansible_facts']['sonic']
    assert 'hwsku' in sonic
    assert 'config_db' not in sonic


def test_unreadable_files_warn(fake_swsscommon, run_module, files, warnings):
    seed(fake_swsscommon)
    files.clear()
    result = run_module(sonic_facts, dict(gather_subset=['all']))
    sonic = result['ansible_facts']['sonic']
    # CONFIG_DB facts and the fallbacks still work.
    assert sonic['platform'] == 'x86_64-kvm_x86_64-r0'
    assert sonic['hwsku'] == 'Force10-S6000'
    assert sonic['hostname'] == 'sonic'
    assert sonic['asic_type'] is None
    assert sonic['version'] is None
    assert sonic['build'] == dict((k, None) for k in EXPECTED_BUILD)
    assert sonic['version_info'] == {}
    assert sonic['config_db']['PORT'] == PORT
    assert 'saved_config_db' not in sonic
    assert len(warnings) == 3
    assert warnings[0].startswith('could not read /etc/sonic/sonic_version.yml: ')
    assert warnings[1].startswith('could not read /etc/sonic/sonic-environment: ')
    assert warnings[2].startswith('could not read /etc/sonic/config_db.json: ')
    assert warnings[2].endswith('; the saved_config_db fact is not available')


