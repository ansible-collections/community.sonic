@pytest.mark.parametrize('check_mode', (True, False))
def test_min_facts(fake_swsscommon, run_module, files, warnings, check_mode):
    seed(fake_swsscommon, mgmt_vrf={'mgmtVrfEnabled': 'true'})
    result = run_module(sonic_facts, dict(), check_mode=check_mode)
    assert result['changed'] is False
    assert warnings == []
    assert fake_swsscommon.writes == []
    sonic = result['ansible_facts']['sonic']
    assert sonic['platform'] == 'x86_64-kvm_x86_64-r0'
    assert sonic['hwsku'] == 'Force10-S6000'
    assert sonic['asic_type'] == 'vs'
    assert sonic['device_type'] == 'LeafRouter'
    assert sonic['hostname'] == 'sonic'
    assert sonic['mac'] == '52:54:00:12:34:56'
    assert sonic['version'] == 'SONiC.202311.0-dirty-20240101.123456'
    assert sonic['kernel'] == '6.1.0-11-2-amd64'
    assert sonic['debian'] == '12.1'
    assert sonic['build'] == EXPECTED_BUILD
    assert sonic['version_info']['sonic_utilities'] == '1.2'
    assert sonic['mgmt_vrf_enabled'] is True
    assert sonic['features'] == {'bgp': 'enabled', 'sflow': 'disabled', 'database': 'always_enabled'}
    assert 'config_db' not in sonic
    assert 'saved_config_db' not in sonic


